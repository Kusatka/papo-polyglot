"""Раздел отчёта ПР №1 «Задания для самостоятельной работы» (подключается из build_report.py)."""


def add_selfwork(r, S, HERE):
    f0, t0 = r.fig, r.tab   # номера следующих рисунков и таблицы
    fig = lambda k: f'рисунок {f0 + k}'
    r.h1('7. Задания для самостоятельной работы')
    r.p(f'Методические указания {r.cite("m1")} предлагают шесть заданий для самостоятельной работы; все '
        f'шесть выполнены на развёрнутом стенде (таблица {t0 + 1}). Данные заданий 2–6 записывались в '
        'отдельные объекты — контейнер `practice01-postgres-init`, база `selfwork` в MongoDB, ключ '
        '`visits:page:/schedule` в Redis, узлы `SNUser` в Neo4j, индекс `books` в Elasticsearch — и после '
        'проверки удалены, чтобы не смешиваться с данными практических работ №2 и №3. Файлы заданий лежат в '
        'каталоге `pr1\\selfwork`, команды всех рисунков раздела — в сценарии `tools\\term_pr1.ps1`.')
    r.table(['№', 'Задание', 'Как выполнено', 'Результат', 'Рис.'], [
        ['1', 'Сменить пароли во всех конфигурациях и проверить работу служб',
         'скрипт `rotate_passwords.py`: смена пароля внутри каждой службы, правка `pr1\\.env` и `lab1\\.env`, '
         'пересоздание контейнеров', 'новые пароли принимаются, прежние отклоняются; веб-интерфейсы и шлюз '
         'ЛР №1 работают; пароли методички возвращены', f'{f0 + 1}, {f0 + 2}'],
        ['2', 'Скрипт инициализации PostgreSQL через /docker-entrypoint-initdb.d',
         '`initdb\\01_schema.sql`, `02_data.sql`, том в `docker-compose.initdb.yml`',
         '3 таблицы, 2 группы, 5 студентов, 15 отметок; при перезапуске инициализация пропущена', str(f0 + 3)],
        ['3', 'MongoDB: вложенные документы и агрегация суммы заказов',
         'коллекция `orders`: покупатель — вложенный документ, позиции — массив; `$unwind`, `$group`, `$multiply`',
         'суммы заказов 88 000, 68 200 и 48 000; по покупателям — 136 000 и 68 200', str(f0 + 4)],
        ['4', 'Redis: счётчик посещений INCR с TTL', '`INCR`, `EXPIRE 10`, `TTL`, ожидание истечения',
         'счётчик 1…6, TTL 10 → 5 → −2, ключ удалён', str(f0 + 5)],
        ['5', 'Neo4j: «друзья друзей» без существующих друзей', '7 пользователей, 8 связей `FRIEND`, шаблон пути '
         'длины 2 с исключением себя и прямых друзей', 'для Анны: Дина (2 общих друга), Глеб, Егор', str(f0 + 6)],
        ['6', 'Elasticsearch: полнотекстовый поиск с ранжированием', 'индекс `books` (10 книг, анализатор '
         '`russian`), `multi_match` с весом названия `title^2`', '7 совпадений, упорядочены по оценке '
         'релевантности `_score`', str(f0 + 7)],
    ], [0.8, 3.6, 5.2, 5.4, 1.5], 'Задания для самостоятельной работы', size=10)

    r.h2('7.1. Смена паролей во всех конфигурациях')
    r.p('Переменные `MONGO_INITDB_ROOT_PASSWORD`, `POSTGRES_PASSWORD`, `NEO4J_AUTH` и `PGADMIN_DEFAULT_PASSWORD` '
        'действуют только при первом запуске контейнера на пустом томе. Для уже инициализированных томов '
        'одной правки `.env` недостаточно: служба продолжит принимать старый пароль, а клиенты с новым '
        'паролем получат отказ. Поэтому скрипт `selfwork\\rotate_passwords.py` выполняет смену в три шага:')
    r.bullets([
        'меняет пароль внутри работающей службы её собственной командой: `ALTER USER` в PostgreSQL, '
        '`changeUserPassword` в MongoDB, `ALTER CURRENT USER SET PASSWORD` в Neo4j, `CONFIG SET requirepass` в '
        'Redis, пароль пользователя pgAdmin;',
        'записывает новые значения в `pr1\\.env` (стенд, mongo-express, Redis Commander, проверки готовности) '
        'и в `lab1\\.env` (строки подключения `PG_DSN` и `REDIS_URL` сервиса ЛР №1);',
        'пересоздаёт контейнеры с изменённой конфигурацией (`docker compose up -d`) и ждёт статуса healthy; '
        'данные остаются в томах.',
    ])
    r.p(f'Затем для каждой службы проверяется вход новым и прежним паролем ({fig(1)}): Redis, PostgreSQL (по '
        'сети Docker, как подключаются клиенты: внутри контейнера локальный вход доверенный), MongoDB, Neo4j и '
        'вход в веб-интерфейс pgAdmin принимают новый пароль и отклоняют прежний; mongo-express отвечает 401 на '
        'старый пароль basic auth; Redis Commander переподключился к Redis с новым паролем; шлюз ЛР №1 '
        'строит отчёт, читая PostgreSQL и Redis по новым строкам подключения.')
    r.figure(S / 't_sw1_pw_new.png', 'Смена паролей во всех конфигурациях и проверка служб')
    r.p(f'Тем же скриптом возвращены пароли методических указаний ({fig(2)}): на них рассчитаны скрипты '
        'практических работ №2–3 и конфигурация ЛР №1. Два наблюдения. Утилита pgAdmin `setup.py update-user` '
        'не принимает пароли короче 6 символов, поэтому пароль методички `admin` записывается напрямую через '
        'модель пользователя pgAdmin (`selfwork\\pgadmin_set_password.py`). В Elasticsearch и Kibana учебной '
        'конфигурации безопасность отключена (`xpack.security.enabled=false`), паролей у них нет; в рабочей '
        'среде её включают и задают пароли встроенных пользователей `elastic` и `kibana_system`.')
    r.figure(S / 't_sw1_pw_back.png', 'Возврат паролей методических указаний и повторная проверка')

    r.h2('7.2. Скрипт инициализации PostgreSQL')
    r.p('Официальный образ PostgreSQL при первом запуске, когда каталог данных пуст, выполняет по алфавиту '
        'файлы `*.sql` и `*.sh` из `/docker-entrypoint-initdb.d`. Скрипты `selfwork\\initdb\\01_schema.sql` '
        '(таблицы групп, студентов и отметок с внешними ключами) и `02_data.sql` (тестовые данные) подключены '
        'туда томом только для чтения. Демонстрация — в отдельном контейнере с новым томом '
        '(`selfwork\\docker-compose.initdb.yml`, порт 5434): том основного стенда уже инициализирован, и '
        f'скрипты на нём не выполнились бы. По журналу контейнера ({fig(3)}) видно, что оба файла выполнены по '
        'порядку, а таблицы и данные созданы; после перезапуска на том же томе образ пишет «Skipping '
        'initialization».')
    r.figure(S / 't_sw2_initdb.png', 'Выполнение скриптов /docker-entrypoint-initdb.d при первом запуске')

    r.h2('7.3. MongoDB: вложенные документы и агрегация')
    r.p(f'Коллекция `orders` в базе `selfwork` хранит заказ одним документом: покупатель — вложенный документ, '
        f'позиции — массив вложенных документов с ценой и количеством ({fig(4)}). Сумма заказа считается '
        'конвейером агрегации: `$unwind` разворачивает позиции, `$group` складывает произведения количества на '
        'цену; второй запрос группирует по покупателю и считает число его заказов.')
    r.code('db.orders.aggregate([{$unwind: "$items"},\n'
           '  {$group: {_id: "$_id", customer: {$first: "$customer.name"}, positions: {$sum: 1},\n'
           '            total: {$sum: {$multiply: ["$items.qty", "$items.price"]}}}},\n'
           '  {$sort: {_id: 1}}])', size=9)
    r.figure(S / 't_sw3_mongo.png', 'MongoDB: заказы с вложенными позициями и агрегация сумм')

    r.h2('7.4. Redis: счётчик посещений с TTL')
    r.p(f'Счётчик посещений страницы — строковый ключ `visits:page:/schedule`, который атомарно увеличивает '
        f'команда `INCR` (ключ создаётся при первом вызове). `EXPIRE 10` задаёт время жизни, `TTL` показывает '
        f'остаток. Через 5 секунд счётчик увеличен ещё раз, и TTL при этом не сбросился. После истечения срока '
        f'`TTL` возвращает −2, `EXISTS` — 0: Redis удалил ключ сам ({fig(5)}).')
    r.figure(S / 't_sw4_redis.png', 'Redis: INCR, EXPIRE и автоматическое удаление ключа')

    r.h2('7.5. Neo4j: «друзья друзей»')
    r.p(f'Граф социальной сети — 7 узлов `SNUser` и 8 связей `FRIEND`; связь дружбы взаимна, поэтому в '
        f'запросах её направление не учитывается. Кандидаты в друзья — узлы на расстоянии двух связей, кроме '
        f'самого пользователя и его прямых друзей; число общих друзей служит рангом рекомендации ({fig(6)}).')
    r.code("MATCH (me:SNUser {name: 'Анна'})-[:FRIEND]-(f)-[:FRIEND]-(fof)\n"
           "WHERE fof <> me AND NOT (me)-[:FRIEND]-(fof)\n"
           "RETURN fof.name AS candidate, count(DISTINCT f) AS mutual_friends, collect(DISTINCT f.name) AS via\n"
           "ORDER BY mutual_friends DESC, candidate", size=9)
    r.figure(S / 't_sw5_neo4j.png', 'Neo4j: граф дружбы и поиск «друзей друзей»')

    r.h2('7.6. Elasticsearch: полнотекстовый поиск с ранжированием')
    r.p(f'Индекс `books` — 10 книг по проектированию систем и данных с полями `title` и `description` '
        f'(встроенный анализатор `russian`: приведение к нижнему регистру, стоп-слова, стемминг), автором, '
        f'годом и тегами. Запрос «масштабируемые системы хранения данных» ищет по названию с весом 2 и по '
        f'описанию; Elasticsearch упорядочивает 7 найденных книг по оценке BM25 `_score`: выше те, где больше '
        f'слов запроса и они реже встречаются в индексе ({fig(7)}). Подсветка показывает, что слова найдены в '
        f'других формах: «систем», «хранение».')
    r.figure(S / 't_sw6_es.png', 'Elasticsearch: индекс books и поиск с ранжированием по релевантности')
