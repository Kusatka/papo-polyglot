r.h2('5.2. Шаг 2 — PostgreSQL: посещаемость за период')
r.bullets([
    'журнал посещаемости — транзакционные данные, его единственная полная и точная копия хранится в '
    'PostgreSQL; процент посещения должен считаться точно по всем отметкам, поэтому агрегат выполняется '
    'там же, где лежат данные (`GROUP BY` на стороне СУБД, в сервис возвращается только 10 строк);',
    'журнал секционирован по неделям; условие `week_start_date BETWEEN <понедельник недели date_from> AND '
    f'date_to` позволяет планировщику отсечь партиции вне периода (partition pruning) '
    f'{r.cite("pg", "pgpart")}: для периода '
    '2026-02-09 … 2026-04-19 читаются 10 недельных партиций из 20 и не читается партиция по умолчанию '
    '(рисунок 11);',
    'точная граница периода задаётся условием на `schedule.scheduled_date`, а занятия — массивом '
    'идентификаторов из шага 1 (`lecture_id = ANY(...)`, индекс `idx_schedule_lecture`);',
    'процент посещения студента = посещённые занятия-лекции с термином / все такие занятия его группы в '
    'периоде × 100, округление до 0,1; сортировка по возрастанию процента, при равенстве — по числу занятий '
    '(больше пропусков при той же доле — выше), затем по id для однозначности; `LIMIT 10`;',
    'для каждого студента собирается список курсов, в лекциях которых встретился термин '
    '(`array_agg(DISTINCT lc.name)`).',
])
r.code('''SELECT a.student_id::text AS student_id,
       count(*)                                 AS total,
       count(*) FILTER (WHERE a.is_present)     AS attended,
       round(100.0 * count(*) FILTER (WHERE a.is_present) / count(*), 1) AS attendance_pct,
       array_agg(DISTINCT lc.name ORDER BY lc.name) AS term_courses
FROM attendance a
JOIN schedule s         ON s.id = a.schedule_id
JOIN lectures l         ON l.id = s.lecture_id
JOIN lecture_courses lc ON lc.id = l.course_id
WHERE s.lecture_id = ANY(%(ids)s::uuid[])
  AND a.week_start_date BETWEEN %(week_from)s AND %(date_to)s       -- отсечение партиций журнала
  AND s.scheduled_date  BETWEEN %(date_from)s AND %(date_to)s
GROUP BY a.student_id
ORDER BY attendance_pct, total DESC, a.student_id
LIMIT %(limit)s''', size=8)
